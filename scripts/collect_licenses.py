"""Collect third-party licence notices into a Markdown file.

Standard library only (importlib.metadata).  Packages that are not installed
in the current environment are listed as "not installed" instead of raising,
so the same script works in dev, CI and portable-build environments.

Usage:
    python scripts/collect_licenses.py [-o OUTPUT]

The default output is ``THIRD_PARTY_NOTICES.md`` in the current directory;
``scripts/build_portable.ps1`` writes it to ``dist/`` and packs it into the
release zip next to ``musicfab.exe``.
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
from pathlib import Path

# distribution names (PyPI), not import names
PACKAGES = [
    # core / IO
    "numpy",
    "scipy",
    "soundfile",
    "setuptools",
    # score / notation
    "mido",
    "music21",
    "pretty_midi",
    # audio DSP (librosa stack)
    "librosa",
    "resampy",
    "soxr",
    # transcription
    "basic-pitch",
    "onnxruntime",
    "mir_eval",
    "scikit-learn",
    "piano_transcription_inference",
    # separation
    "torch",
    "torchaudio",
    "demucs",
    "dora-search",
    "openunmix",
    "einops",
    "julius",
    "lameenc",
    # notation rendering / PDF
    "verovio",
    "pymupdf",
    "resvg-py",
    "cairosvg",
    # tab / GUI
    "pyguitarpro",
    "PySide6",
    # build / test
    "pytest",
    "pyinstaller",
]

