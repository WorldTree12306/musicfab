def _clean_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def _license_from_metadata(meta) -> str:
    expr = meta.get("License-Expression")
    if expr and expr.strip():
        return expr.strip()
    raw = meta.get("License") or ""
    raw = " ".join(raw.split())
    if raw:
        return raw[:160] + ("..." if len(raw) > 160 else "")
    for classifier in meta.get_all("Classifier") or []:
        if classifier.startswith("License ::"):
            return classifier.split("::")[-1].strip()
    return "-"


def _url_from_metadata(meta) -> str:
    homepage = (meta.get("Home-page") or "").strip()
    if homepage:
        return homepage
    for entry in meta.get_all("Project-URL") or []:
        key, _, target = entry.partition(",")
        if key.strip().lower() in {"homepage", "home", "source", "repository"} and target.strip():
            return target.strip()
    return "-"


def _dist_info(name: str) -> tuple[str, str, str]:
    """Return (version, license, url); "not installed" packages never raise."""
    try:
        version = md.version(name)
    except md.PackageNotFoundError:
        return "not installed", "-", "-"
    try:
        meta = md.metadata(name)
    except md.PackageNotFoundError:  # pragma: no cover - defensive
        return version, "-", "-"
    return version, _license_from_metadata(meta), _url_from_metadata(meta)


def render() -> str:
    lines = [
        "# musicfab — third-party notices",
        "",
        "Generated by `scripts/collect_licenses.py`; versions reflect the",
        "environment this file was produced in (packages marked \"not installed\"",
        "are simply absent there).",
        "",
        "## Installed packages",
        "",
        "| Package | Version | License | Project URL |",
        "|---|---|---|---|",
    ]
    for name in PACKAGES:
        version, license_, url = _dist_info(name)
        lines.append(
            f"| {_clean_cell(name)} | {_clean_cell(version)} | "
            f"{_clean_cell(license_)} | {_clean_cell(url)} |"
        )
    lines.append("")
    lines.append(FIXED_NOTES)
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Collect third-package licence notices into a Markdown file."
    )
    parser.add_argument(
        "-o", "--output", default="THIRD_PARTY_NOTICES.md", help="output Markdown path"
    )
    args = parser.parse_args(argv)
    out = Path(args.output)
    if out.parent and str(out.parent):
        out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
